"""Clean copied Built In pages while preserving the employer's full offer."""

import re

from app.services.job_extractors.base import BaseExtractor, ExtractionCandidate


class BuiltInExtractor(BaseExtractor):
    domains = ('builtin.com',)
    page_end = {
        'what the team is saying', 'am i a good fit?', 'the company',
        'view all jobs', 'similar jobs', 'related jobs',
    }

    @staticmethod
    def recognizes_text(text: str) -> bool:
        return 'summary generated by built in' in text.casefold()

    def extract_text(self, text: str) -> ExtractionCandidate:
        lines = [re.sub(r'\s+', ' ', line).strip() for line in text.splitlines() if line.strip()]
        candidate = ExtractionCandidate()
        summary_end = next((i for i, line in enumerate(lines)
                            if line.casefold() == 'summary generated by built in'), None)
        start = summary_end + 1 if summary_end is not None else 0
        # Only infer the copied header's names when its logo boundary is explicit.
        # Body-only pastes remain useful without guessing a title from the prose.
        if summary_end is not None:
            logo = next((i for i in range(summary_end) if re.fullmatch(r'https?://\S+ Logo', lines[i])), None)
            if logo is not None and logo + 2 < summary_end:
                candidate.company, candidate.role = lines[logo + 1:logo + 3]
        body = []
        for line in lines[start:]:
            if line.casefold().rstrip(':') in self.page_end:
                break
            body.append(line)
        candidate.job_description = '\n'.join(body)
        return candidate
