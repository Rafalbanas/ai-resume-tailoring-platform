@pytest.mark.parametrize('url', ['', URL])
def test_builtin_paste_preserves_full_employer_offer_and_explicit_header(url):
    candidate = clean_pasted_offer(PAGE, url)
    assert candidate.company == 'Example Networks'
    assert candidate.role == 'Python Developer with leadership skills'
    assert candidate.job_description == BODY
    assert 'Experience in a Scrum Master role' not in candidate.job_description
    assert '401(k)' not in candidate.job_description


def test_builtin_body_only_does_not_guess_missing_metadata():
    candidate = clean_pasted_offer(BODY, URL)
    assert candidate.company == candidate.role == ''
    assert candidate.job_description == BODY


@pytest.mark.parametrize('source', [BODY, clean_pasted_offer(PAGE).job_description])
def test_employer_sections_keep_requirements_preferences_and_context_distinct(source):
    units, headings = extract_sections(source)
    def categories(quote):
        return {unit.category for unit in units if unit.quote == quote}
    assert categories('Good Unix/Linux competence') == {'mandatory'}
    assert categories('Strong willingness to takeover Scrum Master role') == {'mandatory'}
    assert categories('English to be able to work in international team') == {'mandatory'}
    assert categories('Facilitate Scrum ceremonies and coach the team on Agile practices.') == {'responsibility'}
    assert categories('Polish at the advanced level.') == {'preferred'}
    assert categories('We work in hybrid model, min. 3 days from office') == {'employment'}
    assert categories('Private medical care and training in new technologies.') == {'benefits'}
    assert categories('Learn about our hiring process and equal opportunity policy.') == {'recruitment'}
    assert 'The skills you bring' in headings


def test_builtin_url_jsonld_offer_retains_all_source_content_and_metadata():
    service = JobExtractorService(Settings(_env_file=None))
    posting = {'@type': 'JobPosting', 'title': 'Python Developer with leadership skills',
               'hiringOrganization': {'name': 'Example Networks'}, 'description': BODY}
    candidate, method = service._extract_html(URL, '<script type="application/ld+json">'
                                              + json.dumps(posting) + '</script>')
    assert method == 'jsonld'
    assert candidate.company == 'Example Networks'
    assert candidate.role == posting['title']
    assert candidate.job_description == BODY
